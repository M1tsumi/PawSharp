namespace PawSharp.Core.Enums;

/// <summary>Sort order type used to order posts in a GUILD_FORUM channel.</summary>
public enum SortOrderType
{
    /// <summary>Sort forum posts by activity.</summary>
    LatestActivity = 0,
    /// <summary>Sort forum posts by creation time (from most recent to oldest).</summary>
    CreationDate   = 1,
}
