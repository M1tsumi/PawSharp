namespace PawSharp.Core.Enums;

/// <summary>Layout type used to display posts in a GUILD_FORUM channel.</summary>
public enum ForumLayoutType
{
    /// <summary>No default has been set for the forum channel.</summary>
    NotSet    = 0,
    /// <summary>Display posts as a list.</summary>
    ListView  = 1,
    /// <summary>Display posts as a collection of tiles.</summary>
    GalleryView = 2,
}
